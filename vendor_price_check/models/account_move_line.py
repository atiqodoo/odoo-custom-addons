    # ──────────────────────────────────────────────────────────────
    # NEW: Line-level subtotal including VAT
    # ──────────────────────────────────────────────────────────────
    line_subtotal_incl_vat = fields.Monetary(
        string="Net price(incl. VAT)",
        compute='_compute_line_subtotal_incl_vat',
        store=True,
        readonly=True,
        currency_field='currency_id',
    )

    vendor_promised_cost_vat_incl = fields.Monetary(
        string="Vendor Promised Cost (VAT Incl.)",
        related='purchase_line_id.vendor_promised_cost_vat_incl',
        store=True,
        readonly=True,
        currency_field='currency_id',
    )

    unit_price_vat_incl = fields.Monetary(
        string="Unit Price + VAT",
        compute='_compute_promised_cost_amounts',
        store=True,
        readonly=True,
        currency_field='currency_id',
    )

    promised_cost_difference_vat_incl = fields.Monetary(
        string="Promised Cost Diff. (VAT Incl.)",
        compute='_compute_promised_cost_amounts',
        store=True,
        readonly=True,
        currency_field='currency_id',
    )

    @api.depends('price_subtotal', 'price_total')
    def _compute_line_subtotal_incl_vat(self):
        for line in self:
            # price_total = price_subtotal + tax
            line.line_subtotal_incl_vat = line.price_total

    @api.depends(
        'price_unit',
        'tax_ids',
        'currency_id',
        'product_id',
        'partner_id',
        'move_id.partner_id',
        'vendor_promised_cost_vat_incl',
    )
    def _compute_promised_cost_amounts(self):
        for line in self:
            taxes = line.tax_ids
            partner = line.partner_id or line.move_id.partner_id
            if taxes:
                tax_res = taxes.compute_all(
                    line.price_unit or 0.0,
                    currency=line.currency_id,
                    quantity=1.0,
                    product=line.product_id,
                    partner=partner,
                )
                unit_price_vat_incl = tax_res['total_included']
            else:
                unit_price_vat_incl = line.price_unit or 0.0

            promised_cost = line.vendor_promised_cost_vat_incl or 0.0
            line.unit_price_vat_incl = unit_price_vat_incl
            line.promised_cost_difference_vat_incl = (
                unit_price_vat_incl - promised_cost
                if promised_cost
                else 0.0
            )

    @api.depends(
        'vpc_from_vendor_price_wizard',
        'purchase_line_id',
        'purchase_line_id.volume_reporting_grade_id',
        'purchase_line_id.volume_reference_uom_id',
        'quantity',
        'product_uom_id',
        'price_total',
        'display_type',
    )
    def _compute_bill_grade_values(self):
        for line in self:
            if (
                line.display_type in ('line_section', 'line_note')
                or not line.purchase_line_id
                or not line.product_uom_id
            ):
                line.bill_volume_reporting_grade_id = False
                line.bill_volume_reference_uom_id = False
                line.bill_grade_volume = 0.0
                line.bill_grade_volume_label = False
                line.bill_grade_amount_vat_incl = 0.0
                continue

            purchase_line = line.purchase_line_id
            reference_uom = purchase_line.volume_reference_uom_id
            if not reference_uom:
                try:
                    reference_uom = self.env['product.movement.volume.builder']._get_category_reference_uom(
                        line.product_uom_id
                    )
                except Exception as error:
                    _logger.warning(
                        "VPC_BILL_GRADE_UOM_FAILED line_id=%s product_id=%s uom_id=%s error=%s",
                        line.id,
                        line.product_id.id,
                        line.product_uom_id.id,
                        error,
                    )
                    reference_uom = self.env['uom.uom']

            try:
                grade_volume = line.product_uom_id._compute_quantity(
                    line.quantity or 0.0,
                    reference_uom,
                    round=False,
                ) if reference_uom else 0.0
            except Exception as error:
                _logger.warning(
                    "VPC_BILL_GRADE_VOLUME_FAILED line_id=%s product_id=%s qty=%s error=%s",
                    line.id,
                    line.product_id.id,
                    line.quantity,
                    error,
                )
                grade_volume = 0.0

            formatter_order = purchase_line.order_id
            line.bill_volume_reporting_grade_id = purchase_line.volume_reporting_grade_id
            line.bill_volume_reference_uom_id = reference_uom
            line.bill_grade_volume = grade_volume
            line.bill_grade_volume_label = (
                f"{formatter_order._lpo_report_format_float(grade_volume, 2)} {reference_uom.name}"
                if reference_uom
                else formatter_order._lpo_report_format_float(grade_volume, 2)
            )
            line.bill_grade_amount_vat_incl = line.price_total or 0.0
