# -*- coding: utf-8 -*-

import logging

from odoo import _, api, fields, models
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)


class ProductBarcodePrintWizard(models.TransientModel):
    _name = 'product.barcode.print.wizard'
    _description = 'Product Barcode Print Wizard'

    product_ids = fields.Many2many(
        comodel_name='product.product',
        string='Search Products',
        domain=[('active', '=', True)],
        help='Search and select products to add to the print list.',
    )
    line_ids = fields.One2many(
        comodel_name='product.barcode.print.wizard.line',
        inverse_name='wizard_id',
        string='Labels',
    )
    printer_name = fields.Char(
        string='Windows Printer',
        default=lambda self: self._default_printer_name(),
        required=True,
        help='Exact Windows printer name. Example: BIXOLON SLP-DX420 - BPL-Z.',
    )
    company_title = fields.Char(
        string='Label Title',
        default=lambda self: self.env['barcode.label.config'].get_default_config().label_title,
        required=True,
        help='Short title printed at the top of each label.',
    )
    barcode_source = fields.Selection(
        selection=[
            ('primary', 'Primary Barcode'),
            ('nexx', 'Nexx / Secondary Barcode'),
        ],
        string='Barcode Type',
        default='primary',
        required=True,
        help=(
            'Primary Barcode prints product.barcode generated by '
            'product_barcode_custom. Nexx / Secondary Barcode prints the '
            'imported nexx_barcode field used by POS as a secondary barcode.'
        ),
    )
    config_id = fields.Many2one(
        comodel_name='barcode.label.config',
        string='Label Configuration',
        default=lambda self: self.env['barcode.label.config'].get_default_config(),
        required=True,
    )

    @api.onchange('config_id')
    def _onchange_config_id(self):
        for wizard in self:
            if wizard.config_id:
                wizard.printer_name = wizard.config_id.printer_name
                wizard.company_title = wizard.config_id.label_title

    @api.model
    def _default_printer_name(self):
        config = self.env['barcode.label.config'].get_default_config()
        return config.printer_name or 'BIXOLON SLP-DX420 - BPL-Z'

    def action_add_products(self):
        self.ensure_one()
        if not self.product_ids:
            raise UserError(_('Select at least one product to add.'))

        existing_products = set(self.line_ids.mapped('product_id').ids)
        line_vals = []
        for product in self.product_ids:
            if product.id in existing_products:
                continue
            line_vals.append({
                'wizard_id': self.id,
                'product_id': product.id,
                'label_qty': 1,
                'selected': True,
            })

        if line_vals:
            self.env['product.barcode.print.wizard.line'].create(line_vals)
        self.product_ids = [(5, 0, 0)]
        return self._reload_action()

    def action_clear_lines(self):
        self.ensure_one()
        self.line_ids.unlink()
        return self._reload_action()

    def action_select_all(self):
        self.ensure_one()
        self.line_ids.write({'selected': True})
        return self._reload_action()

    def action_deselect_all(self):
        self.ensure_one()
        self.line_ids.write({'selected': False})
        return self._reload_action()

    def action_print_labels(self):
        self.ensure_one()
        selected = self.line_ids.filtered(lambda line: line.selected and line.label_qty > 0)
        if not selected:
            raise UserError(_('Select at least one line with a label quantity greater than zero.'))

        labels = []
        for line in selected:
            barcode = line._get_print_barcode()
            for _index in range(int(line.label_qty)):
                labels.append({
                    'title': self.company_title,
                    'name': line.product_id.display_name,
                    'barcode': barcode,
                })

        zpl_data = self._build_27mm_two_column_zpl(labels)
        self._send_raw_to_windows_printer(self.printer_name.strip(), zpl_data)

        _logger.info(
            '[manual_barcode_print] printer="%s" labels=%d bytes=%d',
            self.printer_name,
            len(labels),
            len(zpl_data.encode('utf-8')),
        )

        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'type': 'success',
                'message': _(
                    '%(count)d label(s) sent to %(printer)s',
                    count=len(labels),
                    printer=self.printer_name,
                ),
                'sticky': False,
            },
        }

    def _reload_action(self):
        return {
            'type': 'ir.actions.act_window',
            'name': _('Barcode Label Print'),
            'res_model': self._name,
            'res_id': self.id,
            'views': [(False, 'form')],
            'view_mode': 'form',
            'target': 'current',
        }

    def _build_27mm_two_column_zpl(self, labels):
        config = self.config_id or self.env['barcode.label.config'].get_default_config()
        if config.printer_language == 'epl':
            return self._build_27mm_two_column_epl(labels, config)
        rows = []
        for index in range(0, len(labels), 2):
            left = labels[index]
            right = labels[index + 1] if index + 1 < len(labels) else None
            rows.append(
                '^XA\n'
                '^CI28\n'
                '^MD%d\n'
                '^PR%d\n'
                '^PW%d\n'
                '^LL%d\n'
                '^LH0,0\n'
                '%s'
                '%s'
                '^XZ\n'
                % (
                    config.darkness,
                    config.print_speed,
                    config.print_width,
                    config.label_length,
                    self._build_27mm_zpl_panel(left, x_offset=config.left_x, config=config),
                    self._build_27mm_zpl_panel(right, x_offset=config.right_x, config=config) if right else '',
                )
            )
        return ''.join(rows)

    def _build_27mm_two_column_epl(self, labels, config):
        rows = []
        for index in range(0, len(labels), 2):
            left = labels[index]
            right = labels[index + 1] if index + 1 < len(labels) else None
            rows.append(
                'N\n'
                'q%d\n'
                'Q%d,24\n'
                'D%d\n'
                'S%d\n'
                '%s'
                '%s'
                'P1\n'
                % (
                    config.print_width,
                    config.label_length,
                    self._epl_darkness(config),
                    max(1, int(config.print_speed)),
                    self._build_27mm_epl_panel(left, x_offset=config.left_x, config=config),
                    self._build_27mm_epl_panel(right, x_offset=config.right_x, config=config) if right else '',
                )
            )
        return ''.join(rows)

    def _build_27mm_epl_panel(self, label, x_offset, config):
        barcode = self._clean_epl_text(label.get('barcode') or '')
        title = self._clean_epl_text(label.get('title') or 'Mzaramo Paints')[:config.title_max_chars]
        name_lines = self._wrap_label_text(
            label.get('name') or '',
            line_length=config.text_line_chars,
            max_lines=config.text_max_lines,
        )
        line_1 = self._clean_epl_text(name_lines[0] if name_lines else '')
        line_2 = self._clean_epl_text(name_lines[1] if len(name_lines) > 1 else '')
        barcode_width = self._fit_barcode_width(barcode, max(1, int(config.barcode_module_width)), config)
        barcode_x = self._barcode_x_offset(x_offset, barcode, barcode_width, config)
        barcode_type = '3' if config.barcode_type == 'code39' else '1'
        wide_width = max(barcode_width + 1, barcode_width * max(2, int(config.barcode_wide_ratio)))
        return (
            'A%d,%d,0,3,1,1,N,"%s"\n'
            'A%d,%d,0,2,1,1,N,"%s"\n'
            'A%d,%d,0,2,1,1,N,"%s"\n'
            'B%d,%d,0,%s,%d,%d,%d,B,"%s"\n'
        ) % (
            x_offset,
            config.title_y,
            title,
            x_offset,
            config.line_1_y,
            line_1,
            x_offset,
            config.line_2_y,
            line_2,
            barcode_x,
            config.barcode_y,
            barcode_type,
            barcode_width,
            wide_width,
            config.barcode_height,
            barcode,
        )

    def _build_27mm_zpl_panel(self, label, x_offset, config):
        barcode = self._clean_zpl_text(label.get('barcode') or '')
        title = self._clean_zpl_text(label.get('title') or 'Mzaramo Paints')[:config.title_max_chars]
        name_lines = self._wrap_label_text(
            label.get('name') or '',
            line_length=config.text_line_chars,
            max_lines=config.text_max_lines,
        )
        line_1 = name_lines[0] if name_lines else ''
        line_2 = name_lines[1] if len(name_lines) > 1 else ''
        barcode_width = self._fit_barcode_width(barcode, max(1, int(config.barcode_module_width)), config)
        barcode_x = self._barcode_x_offset(x_offset, barcode, barcode_width, config)

        return (
            '^FO%d,%d^A0N,%d,%d^FD%s^FS\n'
            '^FO%d,%d^A0N,%d,%d^FD%s^FS\n'
            '^FO%d,%d^A0N,%d,%d^FD%s^FS\n'
            '%s'
        ) % (
            x_offset,
            config.title_y,
            config.title_font_height,
            config.title_font_width,
            self._zpl_field(title),
            x_offset,
            config.line_1_y,
            config.text_font_height,
            config.text_font_width,
            self._zpl_field(line_1),
            x_offset,
            config.line_2_y,
            config.text_font_height,
            config.text_font_width,
            self._zpl_field(line_2),
            self._build_barcode_command(barcode_x, barcode_width, barcode, config),
        )

    def _barcode_x_offset(self, x_offset, barcode, module_width, config):
        """Estimate Code128 width and center it inside a 27mm panel."""
        if not config.center_barcode:
            return x_offset
        clean = self._clean_zpl_text(barcode)
        encoded_chars = len(clean)
        estimated_width = self._estimate_barcode_width(encoded_chars, module_width, config)
        usable_width = max(1, int(config.panel_width))
        margin = max(2, int((usable_width - estimated_width) / 2))
        return x_offset + margin

    def _fit_barcode_width(self, barcode, preferred_width, config):
        if not config.auto_fit_barcode:
            return max(1, int(preferred_width))
        clean = self._clean_zpl_text(barcode)
        module_width = max(1, int(preferred_width))
        panel_width = max(1, int(config.panel_width))
        while module_width > 1:
            estimated_width = self._estimate_barcode_width(len(clean), module_width, config)
            if estimated_width <= panel_width:
                break
            module_width -= 1
        return module_width

    def _estimate_barcode_width(self, char_count, module_width, config):
        if config.barcode_type == 'code39':
            return module_width * (char_count * 16 + 35)
        return module_width * ((char_count + 3) * 11 + 13)

    def _build_barcode_command(self, x_offset, module_width, barcode, config):
        if config.barcode_type == 'code39':
            return '^FO%d,%d^BY%d,%d,%d^B3N,N,%d,Y,N^FD%s^FS\n' % (
                x_offset,
                config.barcode_y,
                module_width,
                config.barcode_wide_ratio,
                config.barcode_height,
                config.barcode_height,
                self._zpl_field(barcode),
            )
        return '^FO%d,%d^BY%d,%d,%d^BCN,%d,Y,N,N^FD%s^FS\n' % (
            x_offset,
            config.barcode_y,
            module_width,
            config.barcode_wide_ratio,
            config.barcode_height,
            config.barcode_height,
            self._zpl_field(barcode),
        )

    def _send_raw_to_windows_printer(self, printer_name, payload):
        if not printer_name:
            raise UserError(_('Enter a Windows printer name.'))
        try:
            import win32print
        except ImportError as exc:
            raise UserError(_('Direct Windows printing requires pywin32.')) from exc

        payload_bytes = payload.encode('utf-8') if isinstance(payload, str) else payload
        handle = None
        try:
            handle = win32print.OpenPrinter(printer_name)
            win32print.StartDocPrinter(handle, 1, ('Odoo Product Barcodes', None, 'RAW'))
            try:
                win32print.StartPagePrinter(handle)
                win32print.WritePrinter(handle, payload_bytes)
                win32print.EndPagePrinter(handle)
            finally:
                win32print.EndDocPrinter(handle)
        except Exception as exc:
            _logger.error('[manual_barcode_print] failed printer="%s": %s', printer_name, exc, exc_info=True)
            raise UserError(_(
                'Could not print to Windows printer "%(printer)s": %(err)s',
                printer=printer_name,
                err=str(exc),
            ))
        finally:
            if handle:
                win32print.ClosePrinter(handle)

    def _wrap_label_text(self, text, line_length=17, max_lines=2):
        clean = self._clean_zpl_text(text)
        words = clean.split()
        lines = []
        current = ''
        for word in words:
            candidate = (current + ' ' + word).strip()
            if len(candidate) <= line_length:
                current = candidate
                continue
            if current:
                lines.append(current)
            current = word[:line_length]
            if len(lines) >= max_lines:
                break
        if current and len(lines) < max_lines:
            lines.append(current)
        return lines[:max_lines]

    def _clean_zpl_text(self, value):
        value = str(value or '')
        for char in ('^', '~', '\r', '\n', '\t'):
            value = value.replace(char, ' ')
        return ' '.join(value.split())

    def _zpl_field(self, value):
        return self._clean_zpl_text(value).replace('\\', '\\\\')

    def _clean_epl_text(self, value):
        return self._clean_zpl_text(value).replace('"', "'")

    def _epl_darkness(self, config):
        return min(15, max(0, int(config.darkness)))


class ProductBarcodePrintWizardLine(models.TransientModel):
    _name = 'product.barcode.print.wizard.line'
    _description = 'Product Barcode Print Wizard Line'
    _order = 'product_id'

    wizard_id = fields.Many2one(
        comodel_name='product.barcode.print.wizard',
        required=True,
        ondelete='cascade',
    )
    selected = fields.Boolean(string='Print', default=True)
    product_id = fields.Many2one(
        comodel_name='product.product',
        string='Product',
        required=True,
        readonly=True,
    )
    barcode_value = fields.Char(
        string='Barcode',
        compute='_compute_barcode_value',
        store=False,
    )
    label_qty = fields.Integer(string='Labels', default=1)

    @api.depends('product_id', 'wizard_id.barcode_source')
    def _compute_barcode_value(self):
        for line in self:
            line.barcode_value = line._get_print_barcode(raise_if_missing=False)

    def _get_print_barcode(self, raise_if_missing=True):
        self.ensure_one()
        product = self.product_id
        source = self.wizard_id.barcode_source or 'primary'

        if source == 'nexx':
            barcode = product.nexx_barcode or ''
            if not barcode and raise_if_missing:
                raise UserError(_(
                    'Product "%(product)s" has no Nexx / secondary barcode.',
                    product=product.display_name,
                ))
            return barcode

        barcode = product.barcode or ''
        if not barcode:
            barcode = self._generate_primary_barcode(product)
            if barcode and barcode != '0':
                product.write({'barcode': barcode})

        if not barcode and raise_if_missing:
            raise UserError(_(
                'Product "%(product)s" has no primary barcode and one could '
                'not be generated.',
                product=product.display_name,
            ))
        return barcode

    def _generate_primary_barcode(self, product):
        try:
            from odoo.addons.product_barcode_custom.services.barcode_service import (
                generate_simple_barcode,
            )
        except ImportError:
            return product.barcode or ''
        return generate_simple_barcode(str(product.categ_id.id), str(product.id))
